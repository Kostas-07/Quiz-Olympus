const $ = id => document.getElementById(id);
let unlocked = Number(localStorage.getItem("olympusProgress") || 0);
let current = Math.min(unlocked, 11), qi = 0, answered = false, failed = false;
const letters = ["A","B","C","D"];

function drawList(){
  $("gods").innerHTML = "";
  gods.forEach((g,i)=>{
    const b=document.createElement("button");
    b.className="god-item"+(i===current?" active":"")+(i<unlocked?" done":"");
    b.disabled=i>unlocked;
    b.innerHTML=`<span class="num">${String(i+1).padStart(2,"0")}</span><span>${g.emoji}</span><span>${g.name}</span><span class="status">${i<unlocked?"✓":i===unlocked?"●":"🔒"}</span>`;
    if(i===unlocked)b.addEventListener("click",()=>{current=i;startRound()});
    $("gods").appendChild(b);
  });
  $("count").textContent=`${unlocked} / 12`;
  $("percent").textContent=`${Math.round(unlocked/12*100)}%`;
  $("current").textContent=unlocked===12?"Ολοκληρώθηκε":gods[unlocked].name;
}
function startRound(){
  qi=0;failed=false;answered=false;
  $("quiz").classList.remove("hidden");$("victory").classList.add("hidden");
  drawList();showQuestion();
}
function showQuestion(){
  const g=gods[current],q=g.questions[qi];
  $("round").textContent=`ΘΕΟΣ ${String(current+1).padStart(2,"0")} / 12`;
  $("qnum").textContent=`ΕΡΩΤΗΣΗ ${qi+1} / 5`;
  $("bar").style.width=`${(qi+1)*20}%`;
  $("symbol").textContent=g.emoji;$("godname").textContent=g.name;$("domain").textContent=g.domain;
  $("question").textContent=q[0];$("feedback").textContent="";$("feedback").className="";
  $("hint").textContent="Χρειάζεσαι 5/5 σωστές απαντήσεις για να προχωρήσεις.";
  $("next").disabled=true;$("next").textContent=qi===4?"Ολοκλήρωση γύρου →":"Επόμενη ερώτηση →";
  $("answers").innerHTML="";answered=false;
  q[1].forEach((answer,i)=>{
    const b=document.createElement("button");b.className="answer";
    b.innerHTML=`<span class="letter">${letters[i]}</span>${answer}`;
    b.addEventListener("click",()=>choose(i));$("answers").appendChild(b);
  });
}
function choose(i){
  if(answered)return;answered=true;
  const q=gods[current].questions[qi];
  [...$("answers").children].forEach((b,j)=>{b.disabled=true;if(j===q[2])b.classList.add("correct");if(j===i&&i!==q[2])b.classList.add("wrong")});
  if(i===q[2]){$("feedback").textContent="Σωστά! Η γνώση σου σε φέρνει πιο κοντά στον Όλυμπο.";$("feedback").className="feedback good";}
  else{failed=true;$("feedback").textContent=`Λάθος απάντηση. Η σωστή απάντηση είναι: ${q[1][q[2]]}. Θα χρειαστεί να επαναλάβεις όλο τον γύρο.`;$("feedback").className="feedback bad";}
  $("next").disabled=false;
}
function advance(){
  if(!answered)return;
  if(failed){startRound();return;}
  if(qi<4){qi++;showQuestion();return;}
  unlocked++;localStorage.setItem("olympusProgress",String(unlocked));
  if(unlocked===12){drawList();$("quiz").classList.add("hidden");$("victory").classList.remove("hidden");return;}
  current=unlocked;drawList();startRound();
}
$("next").addEventListener("click",advance);
$("reset").addEventListener("click",()=>{if(confirm("Θέλεις σίγουρα να διαγραφεί όλη η πρόοδός σου;")){unlocked=0;current=0;localStorage.removeItem("olympusProgress");startRound();}});
$("again").addEventListener("click",()=>{unlocked=0;current=0;localStorage.removeItem("olympusProgress");startRound();});
drawList();startRound();
